  if (deliveries) deliveries.innerHTML = project.deliverables.map(function (item, index) { return '<article><i>0' + (index + 1) + '</i><span>' + escapeHtml(item) + '</span></article>'; }).join('');

  renderList('[data-project-applies]', project.applies);
  renderList('[data-project-inputs]', project.inputs);
  renderList('[data-project-boundaries]', project.boundaries);

  var neighbours = document.querySelector('[data-project-neighbours]');
  if (neighbours) {
    var previous = projects[(projectIndex - 1 + projects.length) % projects.length];
    var next = projects[(projectIndex + 1) % projects.length];
    neighbours.innerHTML = '<a href="./engineering-detail.html?id=' + encodeURIComponent(previous.id) + '"><span>上一个</span><b>' + escapeHtml(previous.title) + '</b></a><a href="./engineering-detail.html?id=' + encodeURIComponent(next.id) + '"><span>下一个</span><b>' + escapeHtml(next.title) + '</b></a>';
  }
